#!/usr/bin/env python3
"""Generate src/shared/KitData/*.luau and KitIndex.luau from tools/data/kits.json.

kits.json is produced from the compendium .docx by:
    pandoc compendium.docx -t markdown --wrap=none -o doc.md
    python3 tools/parse_compendium.py doc.md tools/data/kits.json
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
kits = json.load(open(os.path.join(ROOT, 'tools', 'data', 'kits.json'), encoding='utf-8'))
out_dir = os.path.join(ROOT, 'src', 'shared', 'KitData')
os.makedirs(out_dir, exist_ok=True)

def q(s):
    if s is None:
        return 'nil'
    s = str(s).replace('\\', '\\\\').replace('"', '\\"').replace('\n', ' ')
    return '"' + s + '"'

def num(v):
    if v is None:
        return 'nil'
    if float(v).is_integer():
        return str(int(v))
    return repr(float(v))

def kid(name):
    return re.sub(r'[^A-Za-z0-9]', '', name)

for f in os.listdir(out_dir):
    if f.endswith('.luau'):
        os.remove(os.path.join(out_dir, f))

index = []
for k in kits:
    i = kid(k['name'])
    index.append((k['num'], k['name'], i, k['tagline']))
    L = ['-- AUTO-GENERATED from the EB: Proxima Ability Compendium by tools/gen_kitdata.py. Do not edit by hand.',
         'return {']
    L.append(f'\tnum = {k["num"]},')
    L.append(f'\tname = {q(k["name"])},')
    L.append(f'\tid = {q(i)},')
    L.append(f'\ttagline = {q(k["tagline"])},')
    L.append(f'\tidentity = {q(k["identity"])},')
    L.append(f'\tpassive = {{ name = {q(k["passive"]["name"])}, text = {q(k["passive"]["text"])} }},')
    L.append('\tmoves = {')
    for m in k['moves']:
        L.append('\t\t{')
        L.append(f'\t\t\tslot = {m["slot"]},')
        L.append(f'\t\t\tname = {q(m["name"])},')
        L.append(f'\t\t\tcd = {num(m["cd"])},')
        L.append(f'\t\t\tenergy = {num(m["energy"])},')
        L.append(f'\t\t\theat = {num(m["heat"])},')
        L.append(f'\t\t\twindup = {num(m["windup"])},')
        L.append(f'\t\t\trange = {num(m["range"])},')
        L.append(f'\t\t\trangeText = {q(m["rangeText"])},')
        L.append(f'\t\t\tstatline = {q(m["statline"])},')
        L.append(f'\t\t\tdesc = {q(m["desc"])},')
        L.append(f'\t\t\tp60 = {q(m.get("p60"))},')
        L.append(f'\t\t\tcounterplay = {q(m.get("counterplay"))},')
        if m.get('unstable'):
            L.append(f'\t\t\tunstable = {q(m["unstable"])},')
        L.append('\t\t},')
    L.append('\t},')
    L.append(f'\tmutation = {{ name = {q(k["mutation"]["name"])}, text = {q(k["mutation"]["text"])} }},')
    L.append(f'\tsequence = {q(k.get("sequence"))},')
    L.append(f'\tteam = {{ partners = {q(k["team"]["partners"])}, text = {q(k["team"]["text"])} }},')
    L.append('}')
    open(os.path.join(out_dir, i + '.luau'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')

L = ['-- AUTO-GENERATED by tools/gen_kitdata.py. Roster in reference-image order.', 'return {']
for n, name, i, tag in index:
    L.append(f'\t{{ num = {n}, name = {q(name)}, id = {q(i)}, tagline = {q(tag)} }},')
L.append('}')
open(os.path.join(ROOT, 'src', 'shared', 'KitIndex.luau'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print(f'generated {len(kits)} kit data modules')
